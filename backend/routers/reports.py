"""Deep research reports routes"""
import os, json, logging
from fastapi import APIRouter, Depends, HTTPException, BackgroundTasks, Query
from typing import Optional, List
from datetime import datetime
from pydantic import BaseModel
from db import get_db
from services.ai_service import chat_complete, extract_json
from routers.auth import require_auth

logger = logging.getLogger(__name__)

router = APIRouter()


class DataSource(BaseModel):
    type: str
    content: Optional[str] = None
    file_url: Optional[str] = None


class TaskRequest(BaseModel):
    title: str
    data_sources: List[DataSource]
    depth: str = "standard"


def _ensure_baseline_report() -> None:
    """Create a completed baseline report when the report center has no data."""
    with get_db() as conn:
        c = conn.cursor()
        c.execute("SELECT COUNT(*) AS cnt FROM insight_tasks WHERE status = %s", ("completed",))
        if c.fetchone()["cnt"] > 0:
            return

        c.execute("""
            SELECT repo_name, language, total, level, recommendation, reasoning
            FROM trending_business_eval
            ORDER BY total DESC NULLS LAST
            LIMIT 5
        """)
        eval_rows = [dict(r) for r in c.fetchall()]
        c.execute("""
            SELECT title, category, summary, last_changed_date
            FROM aliyun_solutions
            WHERE is_active=TRUE
            ORDER BY last_changed_date DESC, id DESC
            LIMIT 8
        """)
        solution_rows = [dict(r) for r in c.fetchall()]

        takeaways = []
        for r in eval_rows[:3]:
            takeaways.append(f"{r.get('repo_name')}: {r.get('level') or 'Pending evaluation'}, recommendation: {r.get('recommendation') or 'Continue tracking business fit'}")
        for r in solution_rows[:3]:
            takeaways.append(f"{r.get('category') or 'Tech solution'}: {r.get('title')}, {r.get('summary') or 'Pending analysis'}")

        result = {
            "summary_metrics": {
                "Project insights count": len(eval_rows),
                "Solution samples": len(solution_rows),
                "Data status": 100 if eval_rows or solution_rows else 60,
            },
            "takeaways": takeaways or ["System has completed baseline inspection, no high-confidence business conclusions yet."],
            "detailed_report": 'This report is auto-generated by the system based on GitHub project insight evaluations and recent solution changes. Use "New Analysis" to generate deep research reports on specific technologies, solutions, or competitors.',
            "strategies": {
                "Short-term": "Prioritize follow-up on high-score open-source projects for enterprise deployment scenarios and customer-demoable solutions.",
                "Mid-term": "Consolidate project insights, solution changes, and competitor capabilities into reusable selection templates.",
            },
        }
        task_id = "baseline_" + datetime.now().strftime("%Y%m%d")
        c.execute("""
            INSERT INTO insight_tasks (id, title, status, data_sources, result)
            VALUES (%s, %s, %s, %s, %s)
            ON CONFLICT (id) DO NOTHING
        """, (
            task_id,
            f"System Baseline Insight Report {datetime.now().strftime('%Y-%m-%d')}",
            "completed",
            json.dumps([{"type": "SYSTEM", "content": "baseline insight from current platform data"}], ensure_ascii=False),
            json.dumps(result, ensure_ascii=False),
        ))


async def run_analysis(task_id: str, title: str, content: str):
    """Run AI analysis logic asynchronously"""
    with get_db() as conn:
        c = conn.cursor()
        c.execute("UPDATE insight_tasks SET status = %s, updated_at = NOW() WHERE id = %s", ("processing", task_id))

    try:
        system_prompt = """You are a world-class business analyst, at the level of McKinsey or Goldman Sachs Research.
Your task is to write a professional, actionable tech solution insight report based on the keywords or data provided by the user.

Output requirements:
1. Must cover four dimensions: technical issues, solution capabilities, competitor comparison, and implementation risks.
2. Must include three solution indices (0-100): technology maturity, integration complexity, and deployment fit.
3. Must include a detailed executive summary and implementation recommendations (short-term and long-term).
4. Tone: professional, objective, direct, using necessary technical terminology, avoiding filler.
5. Must base analysis on available data; if citing external data, note the source and timeliness. Do not fabricate unverified data.
6. Output format: JSON, with fields: summary_metrics, takeaways, detailed_report, strategies."""

        safe_title = title[:200].replace("\n", " ").replace("\"", "'")
        safe_content = content[:5000].replace("\n", " ").replace("\"", "'")
        user_prompt = f"""Task title: {safe_title}
Analysis background data: {safe_content}

Please begin your in-depth analysis."""

        result = chat_complete(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.7, max_tokens=4096,
        )

        parsed = extract_json(result)
        with get_db() as conn:
            c = conn.cursor()
            c.execute(
                "UPDATE insight_tasks SET status = %s, result = %s, updated_at = NOW() WHERE id = %s",
                ("completed", json.dumps(parsed or {"raw": result}, ensure_ascii=False), task_id)
            )
        logger.info("Task %s deep analysis completed", task_id)

    except Exception as e:
        error_msg = str(e)[:500]
        with get_db() as conn:
            c = conn.cursor()
            c.execute(
                "UPDATE insight_tasks SET status = %s, error = %s, updated_at = NOW() WHERE id = %s",
                ("failed", error_msg, task_id)
            )
        logger.warning("Task %s analysis failed: %s", task_id, error_msg)


@router.post("/tasks/analyze")
async def analyze_task(request: TaskRequest, background_tasks: BackgroundTasks, _=Depends(require_auth)):
    from settings import settings
    if not settings.CHAT_API_KEY:
        raise HTTPException(status_code=500, detail="AI service not configured (CHAT_API_KEY missing)")

    task_id = "task_" + os.urandom(4).hex()
    combined_content = ""
    for source in request.data_sources:
        if source.type == "KEYWORD" and source.content:
            combined_content += source.content + "\n"
        elif source.type == "FILE" and source.file_url:
            combined_content += f"[File reference: {source.file_url}]\n"

    with get_db() as conn:
        c = conn.cursor()
        c.execute(
            "INSERT INTO insight_tasks (id, title, status, data_sources) VALUES (%s, %s, %s, %s)",
            (task_id, request.title, "pending",
             json.dumps([s.dict() for s in request.data_sources], ensure_ascii=False))
        )

    background_tasks.add_task(run_analysis, task_id, request.title, combined_content)
    return {"status": "processing", "task_id": task_id, "title": request.title, "message": "Analysis task started"}


@router.get("/tasks/{task_id}")
async def get_task(task_id: str, _=Depends(require_auth)):
    """Query task status and results"""
    with get_db() as conn:
        c = conn.cursor()
        c.execute("SELECT id, title, status, error, result, created_at, updated_at FROM insight_tasks WHERE id = %s", (task_id,))
        row = c.fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Task not found")
    task = dict(row)
    if task.get("result"):
        try:
            task["result"] = json.loads(task["result"]) if isinstance(task["result"], str) else task["result"]
        except (json.JSONDecodeError, TypeError) as e:
            logger.debug("task result JSON parse skip: %s", e)
    return task


@router.get("/reports")
async def list_reports(
    status: Optional[str] = Query(None),
    page: int = Query(1, ge=1),
    page_size: int = Query(10, ge=1, le=50),
    _=Depends(require_auth),
):
    """Get report list"""
    _ensure_baseline_report()
    with get_db() as conn:
        c = conn.cursor()
        where = "WHERE status = 'completed'" if not status else f"WHERE status = %s"
        params = [status] if status else []
        c.execute(f"SELECT COUNT(*) AS cnt FROM insight_tasks {where}", params)
        total = c.fetchone()["cnt"]
        c.execute(
            f"SELECT id, title, status, created_at, updated_at FROM insight_tasks {where} ORDER BY created_at DESC LIMIT %s OFFSET %s",
            params + [page_size, (page - 1) * page_size]
        )
        rows = c.fetchall()
    return {"items": [dict(r) for r in rows], "total": total, "page": page, "page_size": page_size}


@router.get("/reports/{report_id}")
async def get_report(report_id: str, _=Depends(require_auth)):
    """Get report details"""
    with get_db() as conn:
        c = conn.cursor()
        c.execute("SELECT id, title, status, result, error, data_sources, created_at, updated_at FROM insight_tasks WHERE id = %s", (report_id,))
        row = c.fetchone()
    if not row:
        raise HTTPException(status_code=404, detail="Report not found")
    report = dict(row)
    if report.get("result"):
        try:
            report["result"] = json.loads(report["result"]) if isinstance(report["result"], str) else report["result"]
        except (json.JSONDecodeError, TypeError) as e:
            logger.debug("report result JSON parse skip: %s", e)
    if report.get("data_sources"):
        try:
            report["data_sources"] = json.loads(report["data_sources"]) if isinstance(report["data_sources"], str) else report["data_sources"]
        except (json.JSONDecodeError, TypeError) as e:
            logger.debug("report data_sources JSON parse skip: %s", e)
    return report


@router.delete("/reports/{report_id}")
async def delete_report(report_id: str, _=Depends(require_auth)):
    """Delete report"""
    with get_db() as conn:
        c = conn.cursor()
        c.execute("DELETE FROM insight_tasks WHERE id = %s", (report_id,))
        if c.rowcount == 0:
            raise HTTPException(status_code=404, detail="Report not found")
    return {"status": "success", "message": "Report deleted"}
